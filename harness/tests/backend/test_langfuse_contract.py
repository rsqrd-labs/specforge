def test_instrumented_adapter_passes_through_to_wrapped_adapter() -> None:
    """T-123: when wrapped, behaviour must be identical to the unwrapped adapter
    for the caller. Streams must yield the same tokens; complete() must return
    the same string."""
    instrumented_module = import_backend("services.llm.instrumented_adapter")
    InstrumentedAdapter = instrumented_module.InstrumentedAdapter

    base_module = import_backend("services.llm.base")

    class FakeAdapter(base_module.BaseLLMAdapter):
        def __init__(self) -> None:
            self.complete_calls: list[tuple[str, str, int]] = []

        async def stream(self, system: str, user: str, max_tokens: int):
            for token in ["hello", " ", "world"]:
                yield token

        async def complete(self, system: str, user: str, max_tokens: int) -> str:
            self.complete_calls.append((system, user, max_tokens))
            return "complete-response"

    fake = FakeAdapter()
    wrapped = InstrumentedAdapter(
        fake,
        span_id=None,
        provider="anthropic",
        model="claude",
        stage_type="spec",
        action="generate",
    )

    async def run() -> None:
        # stream() must yield identical tokens
        collected: list[str] = []
        async for token in wrapped.stream("sys", "user", 100):
            collected.append(token)
        assert collected == ["hello", " ", "world"], (
            "InstrumentedAdapter.stream must pass through tokens unchanged. "
            "See T-123."
        )

        # complete() must return identical value and forward args
        result = await wrapped.complete("sys-c", "user-c", 50)
        assert result == "complete-response"
        assert fake.complete_calls == [("sys-c", "user-c", 50)], (
            "InstrumentedAdapter.complete must forward args unchanged. See T-123."
        )

    asyncio.run(run())


