def test_existing_adapter_tests_remain_green_when_instrumentation_enabled() -> None:
    """T-123/T-130: the InstrumentedAdapter must be a true pass-through. This
    test verifies by AST inspection that InstrumentedAdapter delegates to
    `wrapped.stream()` and `wrapped.complete()` without altering returns."""
    source = read_backend_file("services", "llm", "instrumented_adapter.py")
    tree = ast.parse(source)

    # Both methods must reference the wrapped adapter
    found_stream_delegation = False
    found_complete_delegation = False
    for node in ast.walk(tree):
        if isinstance(node, ast.AsyncFunctionDef):
            body_src = ast.unparse(node)
            if node.name == "stream" and (
                ".stream(" in body_src or "wrapped.stream" in body_src
            ):
                found_stream_delegation = True
            if node.name == "complete" and (
                ".complete(" in body_src or "wrapped.complete" in body_src
            ):
                found_complete_delegation = True

    assert found_stream_delegation, (
        "InstrumentedAdapter.stream must delegate to the wrapped adapter's "
        "stream(). See T-123."
    )
    assert found_complete_delegation, (
        "InstrumentedAdapter.complete must delegate to the wrapped adapter's "
        "complete(). See T-123."
    )
