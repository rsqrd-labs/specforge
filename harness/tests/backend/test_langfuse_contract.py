def test_instrumented_adapter_records_full_accumulated_stream(
    langfuse_configured: None,
) -> None:
    """T-123: for stream() calls, the full accumulated response is recorded
    exactly once after the stream closes — never per token."""
    import importlib

    import config

    importlib.reload(config)

    instrumented_module = import_backend("services.llm.instrumented_adapter")
    importlib.reload(instrumented_module)
    base_module = import_backend("services.llm.base")

    class FakeAdapter(base_module.BaseLLMAdapter):
        async def stream(self, system: str, user: str, max_tokens: int):
            for token in ["foo", "bar", "baz"]:
                yield token

        async def complete(self, system: str, user: str, max_tokens: int) -> str:
            return ""

    create_calls: list[dict[str, Any]] = []

    async def fake_create_generation(span_id: str | None = None, **kwargs: Any):
        create_calls.append({"span_id": span_id, **kwargs})
        return f"gen-{len(create_calls)}"

    langfuse_service = import_backend("services.langfuse_service")
    monkeypatched = MagicMock()
    monkeypatched.create_generation = fake_create_generation

    with patch.object(langfuse_service, "get_langfuse_client", return_value=monkeypatched):
        wrapped = instrumented_module.InstrumentedAdapter(
            FakeAdapter(),
            span_id="span-1",
            provider="openai",
            model="gpt-4o",
            stage_type="plan",
            action="generate",
        )

        async def run() -> None:
            tokens: list[str] = []
            async for t in wrapped.stream("sys", "user", 200):
                tokens.append(t)
            return tokens

        tokens = asyncio.run(run())

    assert tokens == ["foo", "bar", "baz"], "Stream tokens must pass through unchanged."
    assert len(create_calls) == 1, (
        f"Expected exactly 1 create_generation call per stream; got "
        f"{len(create_calls)}. Streams must accumulate before recording. "
        "See T-123."
    )
    recorded_output = (
        create_calls[0].get("output") or create_calls[0].get("response") or ""
    )
    assert recorded_output == "foobarbaz", (
        f"Recorded output must equal the full accumulated stream; got "
        f"{recorded_output!r}. See T-123."
    )


