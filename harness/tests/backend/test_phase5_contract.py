# T-067 [C1] — Credit service must not use FOR UPDATE on aggregate queries
# ---------------------------------------------------------------------------


def test_credit_deduct_does_not_combine_sum_with_for_update() -> None:
    """
    SELECT SUM(...).with_for_update() is invalid PostgreSQL and raises at runtime.
    The deduct() method must obtain the row lock via a pattern that PostgreSQL accepts.
    Acceptable patterns: SELECT rows FOR UPDATE then sum in Python, or a subquery approach.
    """
    source = read_backend_file("services", "credit_service.py")

    # Find the deduct method body
    deduct_start = source.find("async def deduct")
    assert deduct_start != -1, "credit_service.py must define async def deduct"

    # Find the next method to bound the deduct body
    next_method = source.find("\n    async def ", deduct_start + 1)
    deduct_body = source[deduct_start:next_method] if next_method != -1 else source[deduct_start:]

    # The invalid pattern: func.sum(...).with_for_update() or sum + with_for_update on same statement
    # We flag the combination of func.sum AND with_for_update in a single select() call
    has_sum = "func.sum" in deduct_body or "func.coalesce" in deduct_body
    has_for_update = "with_for_update" in deduct_body

    if has_sum and has_for_update:
        # Check if they appear on consecutive lines (same statement) — that's the bug
        lines = deduct_body.splitlines()
        sum_lines = {i for i, l in enumerate(lines) if "func.sum" in l or "func.coalesce" in l}
        lock_lines = {i for i, l in enumerate(lines) if "with_for_update" in l}
        # If any sum line and lock line are within 4 lines of each other, it's the bad pattern
        for sl in sum_lines:
            for ll in lock_lines:
                assert abs(sl - ll) > 4, (
                    "credit_service.deduct() uses SELECT SUM(...).with_for_update() — "
                    "this is invalid PostgreSQL syntax. Use row-level locking without aggregates. "
                    "See docs/CODE_REVIEW.md [C1] and T-067."
                )


