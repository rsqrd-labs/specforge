@pytest.mark.asyncio
async def test_credit_service_refund_guard_does_not_double_credit() -> None:
    """Calling refund() twice with the same ledger_entry_id must insert only one entry."""
    from uuid import uuid4

    module = import_backend("services.credit_service")
    service = module.CreditService()

    inserted: list = []
    original_entry_id = uuid4()
    original_entry = MagicMock()
    original_entry.id = original_entry_id
    original_entry.amount = -10
    original_entry.user_id = uuid4()
    original_entry.reason = "generate"

    class FakeResult:
        def __init__(self, val):
            self._val = val
        def scalar_one_or_none(self):
            return self._val

    class FakeDB:
        def __init__(self):
            self._inserted = []
            self._call = 0

        async def execute(self, stmt):
            self._call += 1
            if self._call == 1:
                return FakeResult(original_entry)  # first: find the original deduction
            return FakeResult(MagicMock(id=uuid4(), amount=10, reason=f"refund:{original_entry_id}"))  # second: existing refund found

        def add(self, obj):
            self._inserted.append(obj)

        async def flush(self):
            pass

    db = FakeDB()
    # First call exercises the happy path (finds the original deduction).
    await service.refund(db, original_entry_id)

    class IdempotentDB:
        def __init__(self):
            self._inserted = []
            self._call = 0

        async def execute(self, stmt):
            self._call += 1
            if self._call == 1:
                return FakeResult(original_entry)
            # Simulates finding existing refund on second call
            existing_refund = MagicMock()
            existing_refund.reason = f"refund:{original_entry_id}"
            return FakeResult(existing_refund)

        def add(self, obj):
            self._inserted.append(obj)

        async def flush(self):
            pass

    idem_db = IdempotentDB()
    await service.refund(idem_db, original_entry_id)
    assert len(idem_db._inserted) == 0, (
        "refund() inserted a second entry even though a refund already exists for this ledger_entry_id. "
        "See docs/CODE_REVIEW.md [I8] and T-081."
    )


