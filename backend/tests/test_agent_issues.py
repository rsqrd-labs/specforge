"""Tests for agent-ready issues + non-clobbering AGENTS.md (Phase 21 — T-277).

Two pure units:

  - ``task_parser`` enrichment: the agent-ready issue body has all five fixed
    sections (even for a minimal task, via fallbacks), a parseable YAML header
    carrying ``task_ref``/``stage``/``spec_anchors``/``test_path``, the agent
    labels, stable SECTION_CONTRACTS-derived spec anchors, and sanitised free
    text. The Phase-13 ``body_md`` is left untouched (backward compatible).
  - ``agents_md_builder``: writes only inside delimited managed markers,
    round-trips pre-existing user content byte-for-byte, is idempotent
    (deterministic output), and fails safe on a malformed marker pair.
"""

from __future__ import annotations

from services.integrations import agents_md_builder
