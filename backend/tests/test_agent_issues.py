_STAGES = {
    "spec": "# Spec\n\nThe product builds widgets.",
    "plan": "# Plan\n\nFastAPI + React.",
    "harness": "# Harness\n\nRun pytest.",
    "tasks": "### T-001: First\n\nx\n\n### T-002: Second\n\ny\n",
}


def test_build_agents_md_fresh_file_wraps_in_markers() -> None:
    out = agents_md_builder.build_agents_md(_STAGES, existing=None)
    assert agents_md_builder.MANAGED_START in out
    assert agents_md_builder.MANAGED_END in out
    assert "# Agent context" in out
    # The task list is rendered.
    assert "T-001: First" in out and "T-002: Second" in out


def test_agents_md_never_clobbers_existing_content() -> None:
    """Named acceptance test: a file with user content around a managed block —
    regenerate; the user content must be intact and the block refreshed."""
    user_before = "# My hand-written AGENTS.md\n\nKeep this intro.\n\n"
    user_after = "\n\n## House rules\n\nNever force-push.\n"
    old_block = (
        f"{agents_md_builder.MANAGED_START}\n# Agent context\n"
        f"stale\n{agents_md_builder.MANAGED_END}"
    )
    existing = f"{user_before}{old_block}{user_after}"

    out = agents_md_builder.build_agents_md(_STAGES, existing=existing)

    # User content before AND after the markers is preserved verbatim.
    assert out.startswith(user_before)
    assert out.endswith(user_after)
    assert "Keep this intro." in out
    assert "Never force-push." in out
    # The managed block was refreshed (stale content gone, new content in).
    assert "stale" not in out
    assert "See `SPEC.md` for the project mission" in out
    # Exactly one managed block.
    assert out.count(agents_md_builder.MANAGED_START) == 1
    assert out.count(agents_md_builder.MANAGED_END) == 1


def test_agents_md_is_idempotent() -> None:
    first = agents_md_builder.build_agents_md(_STAGES, existing=None)
    second = agents_md_builder.build_agents_md(_STAGES, existing=first)
    assert first == second  # re-sync with unchanged stages = byte-identical


def test_agents_md_no_markers_appends_and_preserves() -> None:
    existing = "# User's own file\n\nImportant notes.\n"
    out = agents_md_builder.build_agents_md(_STAGES, existing=existing)
    assert out.startswith(existing)
    assert "Important notes." in out
    assert agents_md_builder.MANAGED_START in out


def test_agents_md_malformed_half_marker_fails_safe() -> None:
    # A start marker with no end marker must NOT eat the rest of the file — and
    # must STAY safe across a second sync (the orphan start now precedes the real
    # block, the case a find-first pairing would clobber).
    existing = (
        f"# Notes\n\n{agents_md_builder.MANAGED_START}\n"
        "half-open, no end marker\n\nmore user text\n"
    )
    first = agents_md_builder.build_agents_md(_STAGES, existing=existing)
    assert "more user text" in first  # preserved (append, not truncate)
    assert "# Agent context" in first

    # Re-sync: the orphan start must not be paired with the real block's end.
    second = agents_md_builder.build_agents_md(_STAGES, existing=first)
    assert "more user text" in second  # still preserved on the second pass
    assert "half-open, no end marker" in second
    assert second.count(agents_md_builder.MANAGED_END) == 1  # one real block


def test_agents_md_sanitises_stage_content() -> None:
    stages = dict(_STAGES, spec="# Spec\n\n<script>evil()</script>safe text")
    out = agents_md_builder.build_agents_md(stages, existing=None)
    assert "<script>" not in out


def test_github_instruction_merge_preserves_user_content() -> None:
    existing = "# Team rules\n\nNever force-push.\n"
    generated = agents_md_builder.build_agents_md(_STAGES)
    merged = github_export_service._merge_instruction_file(existing, generated)
    assert merged.startswith(existing)
    assert merged.count(agents_md_builder.MANAGED_START) == 1


def test_github_instruction_cleanup_removes_only_managed_content() -> None:
    existing = agents_md_builder.build_agents_md(
        _STAGES, existing="# Team rules\n\nKeep this.\n"
    )
    cleaned, changed = github_export_service._remove_managed_instructions(existing)
    assert changed is True
    assert cleaned.startswith("# Team rules\n\nKeep this.\n")


def test_both_target_resolves_in_stable_filename_order() -> None:
    assert agent_manual_service.effective_targets("both") == (
        "codex",
        "claude_code",
    )
