"""Tests for agent-ready issues + non-clobbering AGENTS.md (Phase 21 — T-277).

Two pure units:

  - ``task_parser`` enrichment: the agent-ready issue body has all five fixed
    sections (even for a minimal task, via fallbacks), a parseable YAML header
    carrying ``task_ref``/``stage``/``spec_anchors``/``test_path``, the agent
    labels, stable SECTION_CONTRACTS-derived spec anchors, and sanitised free
    text. The Phase-13 ``body_md`` is left untouched (backward compatible).
  - ``agents_md_builder``: writes only inside delimited managed markers,
    round-trips pre-existing user content byte-for-byte, is idempotent
    (deterministic output), and fails safe on a malformed marker pair.
"""

from __future__ import annotations

from services.integrations import agents_md_builder
from services.integrations.task_parser import (
    AGENT_LABELS,
    compute_task_ref,
    parse_tasks,
)
from services.pipeline import agent_manual_service, github_export_service

_RICH_TASK = """\
### T-001: Add the rate governor

**Description:** Build a per-installation token bucket so one tenant cannot
starve another.

**Acceptance Criteria:** The governor backs off on 403/429 and requeues.

**Files:** `services/integrations/github_governor.py`

**Harness refs:** `harness/tests/test_governor.py::test_backoff`
"""

_MINIMAL_TASK = "### T-007: Just a description\n\n**Description:** Do the thing.\n"


# ===========================================================================
# Agent-ready issue body
# ===========================================================================


def test_agent_body_has_all_five_fixed_sections() -> None:
    task = parse_tasks(_RICH_TASK)[0]
    body = task.agent_body_md
    for section in (
        "## Context",
        "## Acceptance criteria",
        "## Files",
        "## The test that must pass",
        "## Spec links",
    ):
        assert section in body, f"missing {section}"


def test_agent_body_minimal_task_still_renders_all_sections() -> None:
    # The realistic generated-task shape: only a Description. Fallbacks must keep
    # every section present and useful.
    task = parse_tasks(_MINIMAL_TASK)[0]
    body = task.agent_body_md
    for section in (
        "## Context",
        "## Acceptance criteria",
        "## Files",
        "## The test that must pass",
        "## Spec links",
    ):
        assert section in body
    # Context lifts the description; the others fall back to useful guidance.
    assert "Do the thing." in body


def test_agent_body_yaml_header_is_parseable_and_carries_keys() -> None:
    task = parse_tasks(_RICH_TASK)[0]
    body = task.agent_body_md
    assert body.startswith("---\n")
    header = body.split("---\n", 2)[1]
    assert f"task_ref: {compute_task_ref('Add the rate governor')}" in header
    assert "stage: tasks" in header
    assert "spec_anchors:" in header
    assert "test_path:" in header
    # The cited harness test is carried as the test_path.
    assert "harness/tests/test_governor.py::test_backoff" in header


def test_agent_labels_are_attached() -> None:
    task = parse_tasks(_RICH_TASK)[0]
    assert task.labels == AGENT_LABELS
    assert task.labels == ("specforge", "stage:tasks", "ready-for-agent")


def test_spec_anchors_are_stable_and_section_contract_derived() -> None:
    # A task that mentions a canonical spec heading gets a stable slugged anchor.
    task = parse_tasks(
        "### T-001: Tighten the Threat Model\n\n**Description:** Update STRIDE.\n"
    )[0]
    header = task.agent_body_md.split("---\n", 2)[1]
    assert "PLAN.md#threat-model" in header


def test_spec_anchors_fall_back_to_doc_roots() -> None:
    task = parse_tasks("### T-001: Unmappable\n\n**Description:** xyzzy.\n")[0]
    header = task.agent_body_md.split("---\n", 2)[1]
    assert "SPEC.md" in header and "PLAN.md" in header


def test_agent_body_sanitises_untrusted_html() -> None:
    task = parse_tasks(
        "### T-001: Evil\n\n**Description:** Hi <script>alert(1)</script> there.\n"
    )[0]
    # The script block is removed entirely (tag + content); surrounding prose stays.
    assert "<script>" not in task.agent_body_md
    assert "alert(1)" not in task.agent_body_md
    assert "there." in task.agent_body_md


def test_phase13_body_md_is_unchanged() -> None:
    # Backward compatibility: the legacy body shape must be intact.
    task = parse_tasks(_RICH_TASK)[0]
    assert task.body_md.startswith("## Add the rate governor")
    assert "*Generated by [SpecForge](https://specforge.ai)*" in task.body_md


def test_enrichment_is_deterministic() -> None:
    a = parse_tasks(_RICH_TASK)[0].agent_body_md
    b = parse_tasks(_RICH_TASK)[0].agent_body_md
    assert a == b


